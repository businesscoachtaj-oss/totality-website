#!/usr/bin/env python3
"""Write SoftwareApplication JSON-LD for both apps into pricing.html from data/plans.json.

Run after a price change:  python3 tools/build_schema.py
The block sits between <!-- schema:apps --> and <!-- /schema:apps --> in pricing.html's <head>.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = "https://totality360.com.au"


def money(s):
    return float(re.sub(r"[^0-9.]", "", s))


def offer(name, price, url, desc=None):
    o = {
        "@type": "Offer",
        "name": name,
        "price": f"{price:.2f}",
        "priceCurrency": "AUD",
        "url": url,
        "availability": "https://schema.org/InStock",
        "priceSpecification": {
            "@type": "UnitPriceSpecification",
            "price": f"{price:.2f}",
            "priceCurrency": "AUD",
            "unitCode": "MON",
            "referenceQuantity": {"@type": "QuantitativeValue", "value": 1, "unitCode": "MON"},
        },
    }
    if desc:
        o["description"] = desc
    return o


def build():
    plans = json.load(open(os.path.join(ROOT, "data", "plans.json"), encoding="utf-8"))
    tiers = plans["tiers"]
    t_offers = [offer(t["name"], t["monthlyCents"] / 100, f"{SITE}/pricing.html",
                      f"Up to {t['clientLimit']:,} clients. {t['description']}") for t in tiers]
    t_prices = [t["monthlyCents"] / 100 for t in tiers]
    nut = plans["nutrition"]["plans"]
    n_offers = [offer(p["name"], money(p["monthly"]), f"{SITE}/pricing.html") for p in nut]
    n_prices = [money(p["monthly"]) for p in nut]
    apps = plans.get("apps", {}).get("totality", {})
    nplat = plans["nutrition"].get("platforms", {})

    totality = {
        "@type": "SoftwareApplication",
        "@id": f"{SITE}/#totality-app",
        "name": "Totality",
        "description": "Coaching and gym management software for personal trainers and gyms: programmes, client check-ins, nutrition tracking, messaging, scheduling, billing and classes.",
        "applicationCategory": "BusinessApplication",
        "operatingSystem": "iOS, Android, Web",
        "url": f"{SITE}/totality.html",
        "downloadUrl": [u for u in (apps.get("ios"), apps.get("android"), apps.get("web")) if u],
        "publisher": {"@id": f"{SITE}/#org"},
        "offers": {
            "@type": "AggregateOffer",
            "priceCurrency": "AUD",
            "lowPrice": f"{min(t_prices):.2f}",
            "highPrice": f"{max(t_prices):.2f}",
            "offerCount": len(t_offers),
            "offers": t_offers,
        },
    }
    os_list = ["Android", "Web"] + (["iOS"] if nplat.get("ios") else [])
    nutrition = {
        "@type": "SoftwareApplication",
        "@id": f"{SITE}/#nutrition-app",
        "name": "Totality Nutrition",
        "description": "Calorie and macro tracking app with an Australian food database and barcode scanning.",
        "applicationCategory": "HealthApplication",
        "operatingSystem": ", ".join(os_list),
        "url": f"{SITE}/nutrition.html",
        "downloadUrl": [u for u in (nplat.get("android"), nplat.get("ios"), nplat.get("web")) if u],
        "publisher": {"@id": f"{SITE}/#org"},
        "offers": {
            "@type": "AggregateOffer",
            "priceCurrency": "AUD",
            "lowPrice": f"{min(n_prices):.2f}",
            "highPrice": f"{max(n_prices):.2f}",
            "offerCount": len(n_offers),
            "offers": n_offers,
        },
    }
    graph = {
        "@context": "https://schema.org",
        "@graph": [
            {"@type": "Organization", "@id": f"{SITE}/#org", "name": "Totality 360", "url": f"{SITE}/",
             "sameAs": ["https://instagram.com/totality360au"]},
            totality,
            nutrition,
        ],
    }
    return ("<!-- schema:apps (generated by tools/build_schema.py from data/plans.json) -->\n"
            '<script type="application/ld+json">\n' + json.dumps(graph, indent=2, ensure_ascii=False) +
            "\n</script>\n<!-- /schema:apps -->")


def compare_breadcrumbs():
    """BreadcrumbList on compare.html and compare-*.html (skips a page that already has one)."""
    import glob
    for path in sorted(glob.glob(os.path.join(ROOT, "compare*.html"))):
        name = os.path.basename(path)
        doc = open(path, encoding="utf-8").read()
        if '"BreadcrumbList"' in doc and "<!-- schema:crumbs" not in doc:
            print(f"{name}: has its own BreadcrumbList, left alone")
            continue
        h1 = re.search(r"<h1[^>]*>(.*?)</h1>", doc, re.S)
        title = re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", h1.group(1))).strip() if h1 else name
        items = [{"@type": "ListItem", "position": 1, "name": "Home", "item": f"{SITE}/"}]
        if name == "compare.html":
            items.append({"@type": "ListItem", "position": 2, "name": "Compare", "item": f"{SITE}/compare.html"})
        else:
            items.append({"@type": "ListItem", "position": 2, "name": "Compare", "item": f"{SITE}/compare.html"})
            items.append({"@type": "ListItem", "position": 3, "name": title, "item": f"{SITE}/{name}"})
        block = ("<!-- schema:crumbs (generated by tools/build_schema.py) -->\n"
                 '<script type="application/ld+json">\n' +
                 json.dumps({"@context": "https://schema.org", "@type": "BreadcrumbList", "itemListElement": items},
                            indent=2, ensure_ascii=False) + "\n</script>\n<!-- /schema:crumbs -->")
        if "<!-- schema:crumbs" in doc:
            doc = re.sub(r"<!-- schema:crumbs.*?<!-- /schema:crumbs -->", lambda m: block, doc, count=1, flags=re.S)
        else:
            doc = doc.replace("</head>", block + "\n</head>", 1)
        open(path, "w", encoding="utf-8").write(doc)
        print(f"{name}: BreadcrumbList written")


def main():
    compare_breadcrumbs()
    path = os.path.join(ROOT, "pricing.html")
    doc = open(path, encoding="utf-8").read()
    block = build()
    if "<!-- schema:apps" in doc:
        doc = re.sub(r"<!-- schema:apps.*?<!-- /schema:apps -->", lambda m: block, doc, count=1, flags=re.S)
    else:
        doc = doc.replace("</head>", block + "\n</head>", 1)
    open(path, "w", encoding="utf-8").write(doc)
    print("pricing.html: SoftwareApplication JSON-LD written")


if __name__ == "__main__":
    main()
